-- ============================================================================
-- Alerta Plaga · Esquema de base de datos (Supabase / PostgreSQL)
-- ----------------------------------------------------------------------------
-- Seguridad:
--   * RLS habilitado en todas las tablas.
--   * anon y authenticated NO tienen permisos (el navegador nunca lee la BD).
--   * El backend/bot usa la service_role key, que bypassa RLS.
--   * Aquí NO se guardan tokens, contraseñas ni llaves.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Equipo y avance
-- ---------------------------------------------------------------------------
create table if not exists public.equipos (
  id                text primary key,
  nombre            text not null,
  integrantes       text[] not null default '{}',
  repo              text,
  api_base          text,
  creado_en         timestamptz not null default now(),
  actualizado_en    timestamptz not null default now()
);

create table if not exists public.equipo_avance (
  id                     bigint generated by default as identity primary key,
  equipo_id              text not null references public.equipos(id) on delete cascade,
  puntos                 integer,
  maximo_posible         integer,
  enviados               integer,
  publicados             integer,
  aciertos_total         integer,
  errores_total          integer,
  latencia_mediana_min   numeric(10,2),
  lugar                  integer,
  capturado_en           timestamptz not null default now(),
  raw                    jsonb not null default '{}'::jsonb
);
create index if not exists idx_equipo_avance_equipo
  on public.equipo_avance (equipo_id, capturado_en desc);

-- ---------------------------------------------------------------------------
-- Catálogos oficiales
-- ---------------------------------------------------------------------------
create table if not exists public.plagas (
  id                    text primary key,
  nombre                text not null,
  nombre_cientifico     text,
  nombres_locales       text[] not null default '{}',
  tipo                  text,
  especialidad          text,
  severidad             text not null
    check (severidad in ('baja', 'media', 'alta', 'critica', 'desconocida')),
  cuarentenaria         boolean not null default false,
  cultivos              text[] not null default '{}',
  sintomas              text[] not null default '{}',
  etapas_criticas       jsonb not null default '{}'::jsonb,
  etapas_susceptibles   jsonb not null default '{}'::jsonb,
  actualizado_en        timestamptz not null default now()
);

-- Fila centinela para los casos sin diagnóstico. Permite FK desde casos.plaga_id.
insert into public.plagas (id, nombre, severidad, cuarentenaria)
values ('desconocida', 'Plaga sin identificar', 'desconocida', false)
on conflict (id) do nothing;

create table if not exists public.productores (
  id             text primary key,
  nombre         text not null,
  municipio      text,
  localidad      text,
  parcelas_ids   text[] not null default '{}',
  actualizado_en timestamptz not null default now()
);

create table if not exists public.parcelas (
  id             text primary key,
  productor_id   text references public.productores(id) on delete set null,
  nombre         text,
  municipio      text,
  localidad      text,
  cultivo        text,
  superficie_ha  numeric(10,2) check (superficie_ha is null or superficie_ha >= 0),
  etapa          text,
  lat            double precision check (lat is null or lat between -90 and 90),
  lon            double precision check (lon is null or lon between -180 and 180),
  actualizado_en timestamptz not null default now()
);
create index if not exists idx_parcelas_productor on public.parcelas (productor_id);
create index if not exists idx_parcelas_cultivo   on public.parcelas (cultivo);
create index if not exists idx_parcelas_municipio on public.parcelas (municipio);

create table if not exists public.tecnicos (
  id             text primary key,
  nombre         text not null,
  especialidad   text,
  base           text,
  lat            double precision check (lat is null or lat between -90 and 90),
  lon            double precision check (lon is null or lon between -180 and 180),
  carga          integer check (carga is null or carga >= 0),
  tope           integer check (tope is null or tope >= 0),
  momento        timestamptz,
  actualizado_en timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Mensajes y clasificación
-- ---------------------------------------------------------------------------
create table if not exists public.reportes (
  id             text primary key,
  productor_id   text references public.productores(id) on delete set null,
  parcela_id     text references public.parcelas(id) on delete set null,
  tipo           text not null check (tipo in ('texto', 'voz', 'foto')),
  texto          text,
  audio_url      text,
  foto_url       text,
  duracion_s     numeric(10,2) check (duracion_s is null or duracion_s >= 0),
  lat            double precision check (lat is null or lat between -90 and 90),
  lon            double precision check (lon is null or lon between -180 and 180),
  recibido       timestamptz not null,
  respuesta_a    text references public.reportes(id) on delete set null
                 deferrable initially deferred,
  raw            jsonb not null default '{}'::jsonb,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists idx_reportes_recibido    on public.reportes (recibido desc);
create index if not exists idx_reportes_productor   on public.reportes (productor_id);
create index if not exists idx_reportes_parcela     on public.reportes (parcela_id);
create index if not exists idx_reportes_tipo        on public.reportes (tipo);
create index if not exists idx_reportes_respuesta_a on public.reportes (respuesta_a);

create table if not exists public.casos (
  reporte_id      text primary key references public.reportes(id) on delete cascade,
  es_plaga        boolean not null,
  plaga_id        text references public.plagas(id) on delete set null,
  urgente         boolean not null default false,
  semaforo        text check (semaforo in ('verde', 'amarillo', 'naranja', 'rojo', 'desconocido')),
  tecnico_id      text references public.tecnicos(id) on delete set null,
  prioridad       integer,
  pct             integer check (pct is null or pct between 0 and 100),
  brote           boolean not null default false,
  confianza       numeric(4,3) check (confianza is null or confianza between 0 and 1),
  motor           text,
  razon           text,
  inyeccion       boolean not null default false,
  seguimiento     boolean not null default false,
  seguimiento_de  text,
  raw             jsonb not null default '{}'::jsonb,
  clasificado_en  timestamptz not null default now(),
  actualizado_en  timestamptz not null default now(),
  constraint casos_plaga_coherente check (
    (es_plaga and plaga_id is not null) or
    (not es_plaga and plaga_id is null)
  )
);
create index if not exists idx_casos_plaga       on public.casos (plaga_id);
create index if not exists idx_casos_urgentes    on public.casos (urgente) where urgente;
create index if not exists idx_casos_clasificado on public.casos (clasificado_en desc);
create index if not exists idx_casos_tecnico     on public.casos (tecnico_id);
create index if not exists idx_casos_seguimiento on public.casos (seguimiento_de)
  where seguimiento_de is not null;

-- Registro de envíos a POST /casos. Un reporte se envía UNA sola vez.
create table if not exists public.envios (
  reporte_id     text primary key references public.reportes(id) on delete cascade,
  caso           jsonb not null,
  estado         text not null default 'pendiente'
    check (estado in ('pendiente', 'enviado', 'error', 'duplicado')),
  intentos       integer not null default 0 check (intentos >= 0),
  respuesta      jsonb,
  error          text,
  enviado_en     timestamptz,
  actualizado_en timestamptz not null default now()
);
create index if not exists idx_envios_estado on public.envios (estado);

