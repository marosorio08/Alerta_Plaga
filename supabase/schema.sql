-- ---------------------------------------------------------------------------
-- Marca de actualización automática
-- ---------------------------------------------------------------------------
create or replace function public.actualizar_marca_tiempo()
returns trigger
language plpgsql
as $$
begin
  new.actualizado_en = now();
  return new;
end;
$$;

do $$
declare
  t text;
begin
  foreach t in array array[
    'equipos', 'plagas', 'productores', 'parcelas', 'tecnicos',
    'reportes', 'casos', 'envios', 'avisos', 'preguntas', 'visitas'
  ]
  loop
    execute format('drop trigger if exists trg_%I_actualizado on public.%I', t, t);
    execute format(
      'create trigger trg_%I_actualizado before update on public.%I
       for each row execute function public.actualizar_marca_tiempo()', t, t
    );
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Seguridad: RLS + sin permisos para anon/authenticated
-- ---------------------------------------------------------------------------
do $$
declare
  t record;
begin
  for t in select tablename from pg_tables where schemaname = 'public'
  loop
    execute format('alter table public.%I enable row level security', t.tablename);
    execute format('revoke all on table public.%I from anon, authenticated', t.tablename);
  end loop;
end $$;

do $$
declare
  s record;
begin
  for s in select sequencename from pg_sequences where schemaname = 'public'
  loop
    execute format('revoke all on sequence public.%I from anon, authenticated', s.sequencename);
    execute format('grant all on sequence public.%I to service_role', s.sequencename);
  end loop;
end $$;

grant usage on schema public to service_role;
grant all on all tables in schema public to service_role;

